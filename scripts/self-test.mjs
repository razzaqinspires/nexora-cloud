#!/usr/bin/env node
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
const root = process.cwd();
const read = file => readFile(resolve(root, file), 'utf8');
const pkg = JSON.parse(await read('package.json'));
const compose = await read('compose.yaml');
const bootstrap = await read('scripts/bootstrap.mjs');
const migration = await read('scripts/migrate.mjs');
const docs = await read('app/docs/page.tsx');
const openapi = await read('app/api/v1/openapi.json/route.ts');
const health = await read('app/api/v1/health/route.ts');
const origin = await read('lib/public-origin.ts');
const meta = await read('app/api/v1/meta/route.ts');
const admin = await read('app/api/v1/admin/projects/route.ts');
const eslintConfig = await read('eslint.config.mjs');
const backup = await read('scripts/backup-loop.sh');
const dockerfile = await read('Dockerfile');
const backupDockerfile = await read('Dockerfile.backup');
assert.equal(pkg.scripts.start, 'node scripts/bootstrap.mjs', 'npm start must run the orchestrator');
assert.ok(pkg.scripts['start:app'], 'container must have a separate non-recursive app start command');
for (const [name, version] of Object.entries({next:'16.4.6',react:'19.3.1','react-dom':'19.3.1',pg:'8.23.1',zod:'4.6.7'})) assert.equal(pkg.dependencies[name], version, `${name} must be pinned to the reviewed version`);
assert.ok(pkg.scripts.prebuild, 'Vercel/local build preflight must be wired');
assert.match(compose, /service_completed_successfully/, 'app must wait for migrations');
assert.match(compose, /nexora_pgdata/, 'database must use a persistent named volume');
assert.match(compose, /127\.0\.0\.1:/, 'self-hosted app port must bind to loopback by default');
assert.match(compose, /backup:/, 'automatic backup service must exist');
assert.match(compose, /NEXORA_BACKUP_ENCRYPTION_KEY/, 'backup encryption secret must be configured');
assert.match(bootstrap, /ON CONFLICT|existing|preserv/i, 'bootstrap must preserve existing config/resources');
assert.match(bootstrap, /dockerVolumeExists/, 'bootstrap must inspect the existing database volume before generating secrets');
assert.match(bootstrap, /EXISTING_VOLUME_IDENTITY_KEYS/, 'bootstrap must fail closed when DB identity settings are missing on an existing volume');
assert.match(bootstrap, /function validateEnv/, 'bootstrap must validate database names, users, URLs, ports and backup policy');
assert.match(bootstrap, /Object\.hasOwn\(process\.env/, 'bootstrap must detect even empty environment overrides of critical DB identity and secrets');
assert.match(bootstrap, /without generating replacement credentials/i, 'bootstrap must fail closed instead of rotating secrets when an existing database volume has lost .env');
assert.match(bootstrap, /docker.*compose|compose.*up/s, 'bootstrap must reconcile Docker Compose');
assert.match(bootstrap, /waitForBackupHealthy/, 'bootstrap must verify the first encrypted backup before reporting full readiness');
assert.match(migration, /CREATE TABLE IF NOT EXISTS cloud_projects/, 'migrations must be idempotent');
assert.match(migration, /pg_advisory_lock/, 'migrations must serialize concurrent deploys');
assert.doesNotMatch(migration, /DROP TABLE|TRUNCATE|DELETE FROM cloud_projects/i, 'migration must not destroy project data');
assert.match(docs, /resolvePublicOrigin/, 'developer docs must derive deployment origin dynamically');
assert.match(openapi, /servers:/, 'OpenAPI must publish deployment-specific servers URL');
assert.match(origin, /NEXORA_PUBLIC_URL/, 'canonical domain must be owner-configurable');
assert.match(origin, /VERCEL_URL \|\| process\.env\.VERCEL_PROJECT_PRODUCTION_URL/, 'Preview origin must prefer the current deployment hostname');
assert.match(meta, /canonicalDomainConfigured/, 'metadata must distinguish canonical domain from deployment hostname');
assert.match(admin, /database_not_configured/, 'project registration must return an explicit 503 state when Vercel has no database');
assert.match(admin, /client\?\.release\(\)/, 'admin route must release a database client only after successful acquisition');
assert.match(openapi, /RegisterProjectRequest/, 'OpenAPI must document request schemas');
assert.match(openapi, /ProjectCreatedResponse/, 'OpenAPI must document successful responses');
assert.match(health, /not_configured/, 'health endpoint must expose missing DB without crashing the UI');
assert.match(backup, /openssl enc -aes-256-cbc/, 'backup must be encrypted');
assert.match(backup, /pg_restore --list/, 'backup archive must be verified');
assert.match(backup, /-mac HMAC/, 'backup must authenticate encrypted artifacts');
assert.match(compose, /backup-health\.sh/, 'backup worker must expose a healthcheck');
assert.match(dockerfile, /start:app/, 'container must not recursively call npm start');
assert.match(backupDockerfile, /apt-get install.*openssl/s, 'backup container must explicitly include OpenSSL CLI');
assert.match(eslintConfig, /eslint-config-next\/core-web-vitals/, 'Next.js 16 flat ESLint config must exist');
console.log('NEXORA SELF-TEST PASSED: bootstrap contract, idempotent migrations, dynamic docs, Docker and backup wiring.');
console.log('Note: static tests do not replace Docker deployment, real database migration, backup/restore, or Vercel acceptance tests.');
